-- Jalankan skrip ini di Supabase Dashboard > SQL Editor.
-- Kebijakan di bawah mengizinkan pengunjung mengirim RSVP/ucapan dan membaca ucapan.
-- Pengunjung TIDAK diberi akses membaca daftar RSVP.

create table if not exists public.wedding_rsvps (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 100),
  attendance text not null check (attendance in ('Hadir', 'Tidak hadir')),
  guest_count integer not null default 1 check (guest_count between 1 and 5),
  message text not null default '' check (char_length(message) <= 500),
  created_at timestamptz not null default now()
);

create table if not exists public.wedding_wishes (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 100),
  message text not null check (char_length(message) between 1 and 700),
  created_at timestamptz not null default now()
);

alter table public.wedding_rsvps enable row level security;
alter table public.wedding_wishes enable row level security;

-- Hapus policy dengan nama sama jika skrip dijalankan ulang.
drop policy if exists "Public can submit RSVP" on public.wedding_rsvps;
drop policy if exists "Public can submit wishes" on public.wedding_wishes;
drop policy if exists "Public can read wishes" on public.wedding_wishes;

create policy "Public can submit RSVP" on public.wedding_rsvps
  for insert to anon with check (true);

create policy "Public can submit wishes" on public.wedding_wishes
  for insert to anon with check (true);

create policy "Public can read wishes" on public.wedding_wishes
  for select to anon using (true);

-- Hak minimum untuk role publik yang digunakan browser.
grant insert on table public.wedding_rsvps to anon;
grant insert, select on table public.wedding_wishes to anon;
grant usage, select on sequence public.wedding_rsvps_id_seq to anon;
grant usage, select on sequence public.wedding_wishes_id_seq to anon;
